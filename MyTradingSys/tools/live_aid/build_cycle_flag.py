"""Write cycle_flag_data.js (the daily cycle-bottom flag line) for the live aid page.

  python MyTradingSys/tools/live_aid/build_cycle_flag.py [--asof YYYY-MM-DD]

Reads research/btc_cycles_2026-11/cycle_bottom_flag.py; the page shows the line and marks it stale after 36 h.
"""
import argparse
import json
import sys
from datetime import date, datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESEARCH = HERE.parent.parent / "research" / "btc_cycles_2026-11"
sys.path.insert(0, str(RESEARCH))
import cycle_bottom_flag  # noqa: E402

OUT = HERE / "cycle_flag_data.js"


def render(asof=None, now=None):
    now = now or datetime.now(timezone.utc)
    line = cycle_bottom_flag.flag_line(cycle_bottom_flag.load(), asof or now.date())
    data = {"line": line, "built_utc": now.strftime("%Y-%m-%dT%H:%M:%SZ")}
    return "// generated by build_cycle_flag.py; do not edit\nwindow.CYCLE_FLAG_DATA = " + json.dumps(data) + ";\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--asof", type=date.fromisoformat)
    a = ap.parse_args(argv)
    OUT.write_text(render(a.asof), encoding="utf-8", newline="\n")
    print(OUT)


if __name__ == "__main__":
    sys.exit(main())
