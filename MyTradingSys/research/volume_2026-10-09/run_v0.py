"""V0: data QA + volume magnitudes + time map + event frequencies (outcome-free: no forward return of any event is computed here).
DEV window only (no unseal). Writes V0_RESULTS.md.   Run: python MyTradingSys/research/volume_2026-10-09/run_v0.py
"""
import sys
sys.dont_write_bytecode = True
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import vdata as D  # noqa: E402
import vfeat as F  # noqa: E402

OUT = HERE / "V0_RESULTS.md"
L = []


def p(s=""):
    L.append(s)


def table(head, rows):
    p("| " + " | ".join(head) + " |")
    p("|" + "|".join(["---"] * len(head)) + "|")
    for r in rows:
        p("| " + " | ".join(str(x) for x in r) + " |")
    p()


def q(x, qs=(5, 25, 50, 75, 95, 99)):
    x = x[~np.isnan(x)]
    return [np.percentile(x, k) for k in qs]


def corr(a, b):
    m = ~(np.isnan(a) | np.isnan(b))
    return float(np.corrcoef(a[m], b[m])[0, 1])


d1 = D.load_1d()
h1 = D.load_1h()
d4 = D.load_4h()
p("# V0 RESULTS - BTC volume: data QA, magnitudes, time map (DEV 2020-01-01 .. 2024-06-30, outcome-free)")
p()
p("Generated by run_v0.py on %s. No event forward return is computed in V0. Definitions: PRE_REG_VOLUME_2026-10-09.md." % datetime.now(timezone.utc).strftime("%Y-%m-%d"))
p()
p("## 1. Data QA")
p("- bars: 1d %d (gaps %d), 1h %d (gaps %d), 4h %d (gaps %d); DEV only, HOLDOUT never loaded." % (
    len(d1["t"]), len(D.gaps(d1, D.DAY)), len(h1["t"]), len(D.gaps(h1, D.HOUR)), len(d4["t"]), len(D.gaps(d4, 4 * D.HOUR))))
dd = D.resample(h1, 24)
m = dict(zip(dd["t"], dd["v"]))
rel = np.array([abs(m[t] - v) / v for t, v in zip(d1["t"], d1["v"]) if t in m])
bad = [(datetime.fromtimestamp(t / 1000, timezone.utc).date().isoformat(), round(abs(m[t] - v) / v, 4)) for t, v in zip(d1["t"], d1["v"]) if t in m and abs(m[t] - v) / v > 1e-4]
p("- parity 1h-sum vs 1d archive volume: %d days compared, %d differ by > 0.01 percent: %s (all other days exact). The daily study uses the 1d archive; the 4h study uses the 1h archive." % (len(rel), len(bad), bad))
p("- taker-buy share tbv/v: min %.3f, max %.3f (1d); bars violating o/h/l/c ordering: %d." % (
    (d1["tbv"] / d1["v"]).min(), (d1["tbv"] / d1["v"]).max(), int(((d1["h"] < np.maximum(d1["o"], d1["c"])) | (d1["l"] > np.minimum(d1["o"], d1["c"]))).sum())))
p()

feat = {"1d": F.features(d1, "1d"), "4h": F.features(d4, "4h")}
bars = {"1d": d1, "4h": d4}

p("## 2. Volume magnitudes (what 'volume cannot be hidden' looks like in numbers)")
yrs = sorted({datetime.fromtimestamp(t / 1000, timezone.utc).year for t in d1["t"]})
rows = []
for y in yrs:
    mk = np.array([datetime.fromtimestamp(t / 1000, timezone.utc).year == y for t in d1["t"]])
    v = d1["v"][mk]
    rows.append([y, int(mk.sum()), "%.0f" % np.median(v), "%.0f" % np.percentile(v, 95), "%.0f" % v.max(), "%.3f" % np.mean(d1["tbv"][mk] / v), "%.3f" % np.median(np.abs(np.log(d1["c"][mk] / d1["o"][mk])))])
p("Daily BTC volume (base units, Binance USD-M perp) by year. Volume level drifts by years, which is why every rule below uses RELATIVE volume (RVadj), never absolute thresholds.")
table(["year", "days", "median vol", "p95 vol", "max vol", "mean taker-buy share", "median |daily ret|"], rows)

p("Relative-volume distribution (events use RVadj >= 2 / >= 3 / >= 1.5 / <= 0.8):")
rows = []
for tf in ("1d", "4h"):
    f = feat[tf]
    for nm, arr in (("RV plain", f["rv"]), ("RVadj", f["rvadj"])):
        x = arr[F.W:]
        x = x[~np.isnan(x)]
        rows.append([tf, nm, len(x)] + ["%.2f" % k for k in q(x)] + ["%.1f%%" % (100 * np.mean(x >= 2)), "%.1f%%" % (100 * np.mean(x >= 3)), "%.1f%%" % (100 * np.mean(x <= 0.8))])
table(["tf", "measure", "n", "p5", "p25", "p50", "p75", "p95", "p99", ">=2", ">=3", "<=0.8"], rows)

p("Volume is persistent and linked to volatility (descriptive, contemporaneous and 1-bar-ahead). |ret| = |ln(c/o)|; RR = range / ATR14:")
rows = []
for tf in ("1d", "4h"):
    b, f = bars[tf], feat[tf]
    ret = np.log(b["c"] / b["o"])
    v = b["v"]
    rows.append([tf, "%.2f" % corr(np.log(v[1:]), np.log(v[:-1])), "%.2f" % corr(np.log(v[5:]), np.log(v[:-5])),
                 "%.2f" % corr(np.log(v), np.abs(ret)), "%.2f" % corr(f["rvadj"], f["rr"]),
                 "%.2f" % corr(f["rvadj"][:-1], f["rr"][1:]), "%.3f" % corr(f["rvadj"][:-1], ret[1:]), "%.3f" % corr(f["dp"], ret), "%.3f" % corr(f["dp"][:-1], ret[1:])])
table(["tf", "autocorr ln v lag1", "lag5", "corr(ln v, |ret|)", "corr(RVadj, RR) same bar", "corr(RVadj_i, RR_i+1)", "corr(RVadj_i, ret_i+1)", "corr(DP_i, ret_i) contemporaneous", "corr(DP_i, ret_i+1)"], rows)

p("Next-bar range by today's relative volume (does a volume spike forecast tomorrow's movement? mean RR of the NEXT bar; RR=1 is a typical bar):")
rows = []
edges = [0, 0.7, 1.3, 2, 3, 1e9]
labels = ["<0.7", "0.7-1.3", "1.3-2", "2-3", ">=3"]
for tf in ("1d", "4h"):
    f = feat[tf]
    x, nxt = f["rvadj"][F.W:-1], f["rr"][F.W + 1:]
    row = [tf]
    for lo, hi in zip(edges[:-1], edges[1:]):
        mk = (x >= lo) & (x < hi) & ~np.isnan(nxt)
        row.append("%.2f (n=%d)" % (np.mean(nxt[mk]), int(mk.sum())))
    rows.append(row)
table(["tf"] + labels, rows)

p("## 3. Event frequencies on DEV (n of events per definition; INSUFFICIENT-N threshold: 1d < 30, 4h < 100)")
rows = []
for nm in F.EVENT_NAMES:
    r = [nm, F.DIRS[nm]]
    for tf in ("1d", "4h"):
        n_ev = int(F.events(bars[tf], feat[tf])[nm].sum())
        thr = 30 if tf == "1d" else 100
        r.append("%d%s" % (n_ev, " (INSUFF)" if n_ev < thr else ""))
    rows.append(r)
table(["event", "dir", "1d n", "4h n"], rows)

p("## 4. Time map (DESCRIPTIVE ONLY, never evidence of an edge; 1h bars, UTC)")
t = h1["t"]
hour = ((t % 86400000) // 3600000).astype(int)
day = t // 86400000
month = np.array([datetime.fromtimestamp(x / 1000, timezone.utc).month for x in t])
dayvol = {}
for dd_, vv in zip(day, h1["v"]):
    dayvol[dd_] = dayvol.get(dd_, 0.0) + vv
share = h1["v"] / np.array([dayvol[x] for x in day])
absret = np.abs(np.log(h1["c"] / h1["o"]))
dp = (2 * h1["tbv"] - h1["v"]) / h1["v"]
rows = []
for hh in range(24):
    mk = hour == hh
    sw = mk & np.isin(month, [4, 5, 6, 7, 8, 9, 10])
    wt = mk & ~np.isin(month, [4, 5, 6, 7, 8, 9, 10])
    rows.append([hh, "%.1f%%" % (100 * np.median(share[mk])), "%.1f%%" % (100 * np.median(share[sw])), "%.1f%%" % (100 * np.median(share[wt])),
                 "%.3f%%" % (100 * np.median(absret[mk])), "%+.4f" % np.mean(dp[mk])])
p("Hour-of-day (UTC): median share of the day's volume (all / Apr-Oct / Nov-Mar), median |1h ret|, mean taker delta share DP (buy minus sell as a fraction of volume). Flat would be 4.2%.")
table(["UTC hour", "median vol share", "Apr-Oct", "Nov-Mar", "median |ret|", "mean DP"], rows)
wd = F.slot_keys(d1, "1d")["weekday"]
rows = []
names = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
medall = np.median(d1["v"])
for k in range(7):
    mk = wd == k
    rows.append([names[k], int(mk.sum()), "%.2f" % (np.median(d1["v"][mk]) / medall), "%.3f%%" % (100 * np.median(np.abs(np.log(d1["c"][mk] / d1["o"][mk])))), "%+.4f" % np.mean((2 * d1["tbv"][mk] - d1["v"][mk]) / d1["v"][mk])])
p("Weekday (daily bars): median volume relative to the all-day median, median |daily ret|, mean DP.")
table(["weekday", "days", "volume vs median", "median |ret|", "mean DP"], rows)
mo = np.array([datetime.fromtimestamp(x / 1000, timezone.utc).month for x in d1["t"]])
rows = []
for k in range(1, 13):
    mk = mo == k
    rows.append([k, int(mk.sum()), "%.2f" % (np.median(d1["v"][mk]) / medall), "%.3f%%" % (100 * np.median(np.abs(np.log(d1["c"][mk] / d1["o"][mk]))))])
p("Month of year (daily bars, 2020-2024H1; each month has only 4-5 samples of its own year, so this is shape-only):")
table(["month", "days", "volume vs median", "median |ret|"], rows)

k4 = F.slot_keys(d4, "4h")
f4 = feat["4h"]
valid = np.arange(len(d4["t"])) >= F.W
rows = []
for s in range(6):
    mk = (k4["slot"] == s) & valid
    rows.append(["%02d-%02d" % (4 * s, 4 * s + 4), int(mk.sum()), "%.1f%%" % (100 * np.mean(f4["rv"][mk] >= 2)), "%.1f%%" % (100 * np.mean(f4["rvadj"][mk] >= 2)),
                 "%.1f%%" % (100 * np.mean(f4["rv"][mk] >= 3)), "%.1f%%" % (100 * np.mean(f4["rvadj"][mk] >= 3))])
p("What the time adjustment removes (4h): share of bars in each slot that qualify as a 'spike' with PLAIN relative volume vs TIME-ADJUSTED relative volume. If volume had no daily rhythm, every row would be equal.")
table(["slot UTC", "bars", "plain RV>=2", "RVadj>=2", "plain RV>=3", "RVadj>=3"], rows)
wk = k4["weekend"] & valid
wd_ = (~k4["weekend"]) & valid
p("Weekend vs weekday (4h): share of bars with RVadj>=3: weekend %.2f%%, weekday %.2f%%; with plain RV>=3: weekend %.2f%%, weekday %.2f%%." % (
    100 * np.mean(f4["rvadj"][wk] >= 3), 100 * np.mean(f4["rvadj"][wd_] >= 3), 100 * np.mean(f4["rv"][wk] >= 3), 100 * np.mean(f4["rv"][wd_] >= 3)))
p()
OUT.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
print("wrote", OUT, len(L), "lines")
