"""Builds DEV_CHECK.md and the VERDICTS.csv rows from run_out/dev_shift*.json. No number is typed by hand."""
import csv
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
OUT = HERE / "run_out"
J = {s: json.loads((OUT / f"dev_shift{s:+d}.json").read_text()) for s in (0, 1, -1)}
CNT = json.loads((OUT / "dev_count.json").read_text())
R = ["R1", "R2", "R3", "R4", "R5"]


def f(x, d=3):
    return "n/a" if x != x else f"{x:.{d}f}"


def cell(s, r):
    x = J[s]["rules"][r]
    return f"n={x['n']}, {f(x['mean_net_r'])} R, p={f(x['p'], 4)}, Holm {f(x['holm_p'], 4)}"

L = []
L.append("# Rumers DEV check: 5 frozen rules, BTCUSDT 1m, DEV 2022-04-01..2024-06-30, fee-net (2026-11-04)\n")
L.append("Generated by `gen_dev_check.py` from `run_out/dev_shift*.json` (runner `run_dev.py`, test "
         "`tests/research/test_rumers_run_dev.py`). Rules, thresholds and m=5 are FROZEN in PRE_REG.md. VALIDATION and HOLDOUT never read: "
         f"only the {len(J[0]['sha256'])} month files 2022-01..2024-06 were opened ({J[0]['bars_1m']} 1m bars); sha256 per file is in each "
         "`run_out/dev_*.json`. A DEV pass is a hypothesis for ONE VALIDATION read, never a promotion.\n")
L.append("Fees: `BINANCE_TAKER*2` = 0.10 % round trip (SOURCED fees.py); stress column 0.14 % (SOURCED research_kit.TAKER_RT_PCT). "
         "SE day-clustered, p two-sided normal, Holm over m=5.\n")
L.append("## Result (shift 0)\n")
L.append("| Rule | n | hit-rate | mean net R | SE | p | Holm p | mean net R @0.14 % | verdict | shift +1 | shift -1 |")
L.append("|---|---|---|---|---|---|---|---|---|---|---|")
for r in R:
    x = J[0]["rules"][r]
    L.append(f"| {r} {x['name']} | {x['n']} | {f(x['hit_rate'], 3)} | {f(x['mean_net_r'])} | {f(x['se'])} | {f(x['p'], 4)} | "
             f"{f(x['holm_p'], 4)} | {f(x['mean_net_r_stress'])} | **{x['verdict']}** | {cell(1, r)} | {cell(-1, r)} |")
L.append("\nVerdict rule (OURS): n < 30 NOT ENOUGH DATA; mean > 0 and Holm p < 0.05 and n >= 100 PASS-DEV; mean <= 0 and n >= 100 FAIL; "
         "else INCONCLUSIVE.\n")
L.append("## Triggers, geometry, exits (shift 0)\n")
L.append("| Rule | triggers (count-only) | valid entry geometry | traded (one position at a time) | median stop % | gross R | longs | exit kinds |")
L.append("|---|---|---|---|---|---|---|---|")
for r in R:
    x, c = J[0]["rules"][r], CNT["rules"][r]
    L.append(f"| {r} | {c['triggers']} | {c['valid_geometry_before_overlap']} | {x['n']} | {f(x['median_stop_pct'], 2)} | "
             f"{f(x['mean_gross_r'])} | {x['longs']} | {x['exit_kinds']} |")
L.append("\n## Claimed by video vs measured\n")
x4 = J[0]["rules"]["R4"]
L.append("| Rule | claim | measured |\n|---|---|---|")
for r in R:
    x = J[0]["rules"][r]
    if r == "R4":
        L.append(f"| R4 | \"most of the trades, 80% or more ... long\" (SOURCED, PRE_REG) | longs {x['longs']} of {x['n']} "
                 f"= {f(x['longs'] / x['n'] if x['n'] else float('nan'), 2)} (DEV has both Daily-SMA50 regimes) |")
    else:
        L.append(f"| {r} | NOT_IN_DATA (video gives no hit-rate or RR) | hit-rate {f(x['hit_rate'], 3)}, mean net R {f(x['mean_net_r'])} |")
L.append("\n## Look-ahead gates (PRE_REG s.3)\n")
L.append("| Rule | mean net R shift -1 (leak) | shift 0 | shift +1 (delayed) | read |\n|---|---|---|---|---|")
for r in R:
    a, b, c = (J[s]["rules"][r]["mean_net_r"] for s in (-1, 0, 1))
    rd = ("-1 better than 0: OK" if a > b else "-1 NOT better: code suspect") + "; " + (
        "+1 worse: OK" if c < b else "+1 not worse (within noise at this n)" if J[0]["rules"][r]["n"] < 100 else "+1 NOT worse: check")
    L.append(f"| {r} | {f(a)} | {f(b)} | {f(c)} | {rd} |")
L.append("\nShift -1 enters on the open of the signal bar itself (before its close is known) with the stop and target the bar produced; "
         "it is a leak probe, never a result. Huge shift -1 means (tiny risk distances when the entry open sits next to the wick stop) "
         "are the leak, not edge.\n")
L.append("## Parameters: SOURCED vs OURS\n")
L.append("| Parameter | Label |\n|---|---|")
for k, v in [
    ("Triggers, stops, targets, thresholds (20 %/25 % ATR, 1.5 ATR, RSI 70/30, PDH/PDL, 5-bar fractal) as in PRE_REG.md", "SOURCED per PRE_REG (frozen)"),
    ("Fees 0.10 % round trip, stress 0.14 %", "SOURCED (fees.py, research_kit)"),
    ("Entry next 1m open after the signal bar closes; stop first on same-bar hit; gap exits at the open if beyond the stop", "SOURCED harness convention / OURS gap fill"),
    ("Tick 0.1 USDT", "OURS"),
    ("Sessions 00:00 and 13:30 UTC for R1 and R4; daily ATR(14) = SMA of true range of the 14 prior full UTC days", "OURS"),
    ("R1 reversal bar = 5m pin (wick >= 50 % of range, closes against the 15m move) within 12 bars, break by a 5m CLOSE within 6 bars", "OURS"),
    ("R4 reversal bar = first 5m bar closing with the Daily-SMA50 trend within 12 bars, 'crossover' = 5m close beyond its extreme within 6 bars; day extreme = UTC-day extreme so far", "OURS"),
    ("R2: first sweep per day and side only; Target 1 (midpoint) only, Target 2 not run; both sides in one bar skipped", "OURS"),
    ("R3: Daily VWAP = UTC-day typical-price VWAP on 5m; reversal candle = first 5m bar within 6 bars closing toward VWAP; no divergence required; target = VWAP at the reversal bar close (fixed level)", "OURS"),
    ("R5: 15m sucker = 2+ consecutive same-colour candles ending in the outer 25 % of the 1h fractal range, confirmation = next candle of opposite colour, trigger = a 15m close beyond its extreme within 4 bars; partial 50 % at 1R then break-even stop", "OURS"),
    ("One open position per rule; 7-day time stop at the close; exits past 2024-06-30 closed at the last DEV bar", "OURS"),
    ("N gate 100, minimum n 30", "OURS"),
]:
    L.append(f"| {k} | {v} |")

passed = [r for r in R if J[0]["rules"][r]["verdict"] == "PASS-DEV"]
failed = [r for r in R if J[0]["rules"][r]["verdict"] == "FAIL"]
other = [r for r in R if r not in passed + failed]
bx = max((r for r in R if J[0]["rules"][r]["n"] >= 30), key=lambda r: J[0]["rules"][r]["mean_net_r"])
b = J[0]["rules"][bx]
L.append("\n## What MTS can use\n")
L.append(f"1. PASS-DEV at shift 0: {', '.join(passed) if passed else 'none'}. " + (
    "These are a hypothesis for one VALIDATION read." if passed else "No Rumers rule earns a VALIDATION read from this run."))
L.append(f"2. Closed (FAIL, fee-net mean <= 0 at n >= 100): {', '.join(failed) if failed else 'none'}.")
L.append(f"3. Not decided (n too small after the frozen filters): {', '.join(other) if other else 'none'}; "
         + "; ".join(f"{r} n={J[0]['rules'][r]['n']}" for r in other) + " (one redesign allowed each, none made here).")
L.append(f"4. Highest mean net R with n >= 30: {bx} n={b['n']}, {f(b['mean_net_r'])} R, Holm p={f(b['holm_p'], 4)}; "
         f"at the 0.14 % stress cost {f(b['mean_net_r_stress'])} R.")
L.append("5. Gross R before fees vs mean net R (fee drag = gross - net): " + "; ".join(f"{r} {f(J[0]['rules'][r]['mean_gross_r'], 2)} -> {f(J[0]['rules'][r]['mean_net_r'], 2)} (median stop {f(J[0]['rules'][r]['median_stop_pct'], 2)} %)" for r in R) + ".")
(HERE / "DEV_CHECK.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")

# VERDICTS.csv rows (columns of research/VERDICTS.csv)
sha = subprocess.run(["git", "-C", str(REPO), "rev-parse", "--short=8", "HEAD"], capture_output=True, text=True).stdout.strip()
rows = []
sys.path.insert(0, str(REPO))
from MyTradingSys.backtest.fees import BINANCE_TAKER  # noqa: E402
FEE_RT_PCT = round(BINANCE_TAKER * 2 * 100, 2)
for r in R:
    x = J[0]["rules"][r]
    rows.append({"study_dir": "rumers_2026-11-01", "family": "Rumers frozen rules (PRE_REG m=5), BTCUSDT 1m DEV",
                 "arm": f"{r} {x['name']}", "split_read": "DEV", "n": x["n"], "gross_mean_pct": "n/a",
                 "se_pct": "n/a", "fee_rt_pct": FEE_RT_PCT, "verdict": x["verdict"],
                 "kill_scope": f"this frozen encoding only (PRE_REG.md, OURS fills in DEV_CHECK.md): mean net R {f(x['mean_net_r'])}, "
                               f"Holm p {f(x['holm_p'], 4)}; says nothing about the analyst's discretionary reads, other markets or 2024-07+.",
                 "one_run": "yes", "commit": sha, "date": "2026-11-04"})
p = REPO / "MyTradingSys" / "research" / "VERDICTS.csv"
txt = p.read_bytes().decode("utf-8")
nl = "\r\n" if "\r\n" in txt else "\n"
import io
buf = io.StringIO()
w = csv.DictWriter(buf, fieldnames=["study_dir", "family", "arm", "split_read", "n", "gross_mean_pct", "se_pct", "fee_rt_pct", "verdict",
                                    "kill_scope", "one_run", "commit", "date"], lineterminator=nl)
for row in rows:
    w.writerow(row)
if not txt.endswith(("\n", "\r\n")):
    txt += nl
if "rumers_2026-11-01" not in txt:
    p.write_bytes((txt + buf.getvalue()).encode("utf-8"))
print("DEV_CHECK.md written; verdict rows:", len(rows))
