"""Imbalance filter on the lc-levels-hold level layer: DEV run (PRE_REG.md in this folder).

  python run_filter.py counts   -> events_dev.csv, COUNTS.md      (first touches + imbalance flags; NO outcome column; heavy: about 10 minutes)
  python run_filter.py run      -> trades_dev.csv, trials.csv, RESULT.md   (ONE outcome run; refuses to run twice)

Reads only 1m month files <= 2024-06 (filter_join.load_dev_1m). Rules are the ones frozen in PRE_REG.md; nothing is tuned here.
"""
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import filter_join as F  # noqa: E402

DAY = F.DAY
K_COLS = {2.0: "", 3.0: "_k3"}
TF_LABEL = {"1h": "1h", "4h": "4h", "12h": "12h", "1d": "1d"}


def write(out, name, text):
    (out / name).write_text(text, encoding="utf-8", newline="\n")


def md_table(rows, cols, fmt=None):
    fmt = fmt or {}

    def cell(r, c):
        v = r.get(c, "")
        if isinstance(v, (float, np.floating)):
            if v != v:
                return "n/a"
            return fmt.get(c, "{:.4f}").format(v)
        return str(v)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(cell(r, c) for c in cols) + " |" for r in rows]
    return "\n".join(out)


# ------------------------------------------------------------------ counts (no outcome)
def counts(df=None, out=HERE, first_day=F.FIRST_DAY, last_day=F.LAST_DAY, block=30):
    t0 = time.time()
    df = F.load_dev_1m() if df is None else df
    print("bars", len(df), pd.Timestamp(int(df.t.min()), unit="ms"), pd.Timestamp(int(df.t.max()), unit="ms"), flush=True)
    tables = {tf: F.candle_table(df, tf) for tf in F.TFS}
    levels = F.levels_blocks(df, first_day, last_day, F.KEEP, block=block)
    print("levels built", round(time.time() - t0), "s", flush=True)
    # level blocks equal a 40-day window on three seeded days
    rng = np.random.default_rng(20261016)
    checks = []
    day = df.t.to_numpy() // DAY
    pool = np.arange(first_day + 40, last_day)
    for d in sorted(int(x) for x in (rng.choice(pool, 3, replace=False) if len(pool) >= 3 else [])):
        sub = df[(day >= d - 40) & (day <= d)]
        full = F.lv.levels_by_day(sub[["t", "o", "h", "l", "c", "v"]].to_dict("records")).get(d, [])
        a = sorted((x["family"], x["price"]) for x in full if x["family"] in F.KEEP)
        b = sorted((x["family"], x["price"]) for x in levels[d])
        checks.append((str(pd.Timestamp(d * DAY, unit="ms").date()), len(a), a == b))
    print("level-block checks", checks, flush=True)
    ev, skips = F.build_events(df, first_day=first_day, last_day=last_day, levels=levels)
    for k, suf in K_COLS.items():
        ev = F.attach_flags(ev, tables, k, suffix=suf)
    ev.drop(columns=["gidx", "eidx"]).to_csv(out / "events_dev.csv", index=False, lineterminator="\n", float_format="%.8g")
    write(out, "COUNTS.md", counts_md(ev, skips, checks))
    print("done", round(time.time() - t0), "s", flush=True)


def counts_md(ev, skips, checks):
    n = len(ev)
    half = np.where(ev.day < F.H2_START_DAY, "H1", "H2")
    imb, large, ctrl = ev["small"], ev["large"], ev["ctrl"]
    ctrl_only = ctrl & ~imb
    share = lambda m: f"{int(m.sum())} ({100 * m.mean():.1f} %)"      # noqa: E731
    fam = ev.family.str.split("|").str[0].value_counts()
    L = ["# COUNTS: first touches of the lc-levels-hold KEEP levels and the imbalance flags (no outcome column; generated by `run_filter.py counts`)", "",
         f"DEV only: UTC days 2022-04-01..2024-06-30, 1m bars with open < 2024-07-01. Level blocks equal a 40-day window on 3 seeded days: "
         + "; ".join(f"{d} ({m} levels) {'equal' if ok else 'DIFFERENT'}" for d, m, ok in checks) + ".", "",
         f"- Touch events (deduplicated, one per level price and day): **{n}** on {ev.day.nunique()} days; H1 {int((half == 'H1').sum())}, H2 {int((half == 'H2').sum())}.",
         f"- Skipped and counted: incomplete days {skips['incomplete_day']}; levels seen {skips['levels']}; touched {skips['touched']}; "
         f"touched but side ambiguous (previous close equals the level) {skips['ambiguous_side']}.",
         f"- Median width {ev.w_pct.median():.3f} % of price (cost 0.14 % = {0.14 / ev.w_pct.median():.2f} R at the median).", "",
         "## Flag sizes (a trade can carry several)", "",
         "| group | n (share of touches) | days | H1 | H2 |", "|---|---|---|---|---|"]
    for name, m in [("SMALL k2 (IMB)", imb), ("no SMALL k2 (NOIMB)", ~imb), ("LARGE k2", large), ("no LARGE k2", ~large), ("CTRL only (shape, no volume)", ctrl_only),
                    ("SMALL k3", ev["small_k3"]), ("LARGE k3", ev["large_k3"])]:
        L.append(f"| {name} | {share(m)} | {ev.day[m].nunique()} | {int((m & (half == 'H1')).sum())} | {int((m & (half == 'H2')).sum())} |")
    L += ["", "## SMALL k2 by timeframe", "", "| tf | n (share) |", "|---|---|"]
    L += [f"| {tf} | {share(ev[f'small_{tf}'])} |" for tf in F.TFS]
    L += ["", "## Touches by family (first family of a joined price)", "", "| family | n |", "|---|---|"]
    L += [f"| {k} | {v} |" for k, v in fam.items()]
    sh = imb.mean()
    L += ["", "## Gates (PRE_REG sections 4 and 6)", "",
          f"- n_IMB {int(imb.sum())} (>= 200: {'yes' if imb.sum() >= 200 else 'NO'}), n_NOIMB {int((~imb).sum())}, IMB days {ev.day[imb].nunique()} (>= 100: {'yes' if ev.day[imb].nunique() >= 100 else 'NO'}), n_LARGE {int(large.sum())} (>= 200: {'yes' if large.sum() >= 200 else 'NO'}).",
          f"- Degenerate-share check (< 2 % or > 90 %): SMALL k2 share {100 * sh:.1f} %, LARGE k2 share {100 * large.mean():.1f} %: "
          f"{'DEGENERATE, read as weak' if (sh < 0.02 or sh > 0.9 or large.mean() < 0.02 or large.mean() > 0.9) else 'not degenerate'}.",
          f"- Naive MDE of Delta1 at 80 % power, trades treated as independent with SD 1 R: {2.8 * (1 / max(imb.sum(), 1) + 1 / max((~imb).sum(), 1)) ** 0.5:.3f} R "
          "(a lower bound; the day-clustered MDE is printed in RESULT.md)."]
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------ the one outcome run
def cell_row(name, block, sim, mask, rr):
    g = sim[mask]
    s = F.stats(g[f"net_{rr:g}"].to_numpy(), g["day"].to_numpy())
    kinds = g[f"kind_{rr:g}"].value_counts(normalize=True)
    return {"cell": name, "block": block, "rr": rr, "n": s["n"], "days": s["days"],
            "target %": 100 * kinds.get("target", 0.0), "stop %": 100 * kinds.get("stop", 0.0), "time %": 100 * kinds.get("time", 0.0),
            "gross R": g[f"gross_{rr:g}"].mean(), "cost R": g[f"cost_{rr:g}"].mean(), "net R": s["mean"], "SE": s["se"], "t": s["t"],
            "net R maker-in": g[f"net_m_{rr:g}"].mean()}


def diff_row(name, block, sim, ma, mb, rr):
    a, b = sim[ma], sim[mb]
    col = f"net_{rr:g}"
    d = F.diff_stats(a[col].to_numpy(), a["day"].to_numpy(), b[col].to_numpy(), b["day"].to_numpy())
    return {"cell": name, "block": block, "rr": rr, "n_a": len(a), "n_b": len(b), "diff R": d["diff"], "SE": d["se"], "t": d["t"], "p": d["p"], "MDE R": d["mde"]}


def run(df=None, out=HERE):
    if (out / "RESULT.md").exists() or (out / "trades_dev.csv").exists():
        raise SystemExit("one run: RESULT.md or trades_dev.csv already exists (PRE_REG.md section 0)")
    if not (out / "COUNTS.md").exists() or not (out / "events_dev.csv").exists():
        raise SystemExit("run `run_filter.py counts` first (PRE_REG.md section 0)")
    t0 = time.time()
    df = F.load_dev_1m() if df is None else df
    ev = pd.read_csv(out / "events_dev.csv")
    bar_t = df.t.to_numpy()
    ev["gidx"] = np.searchsorted(bar_t, ev["t"].to_numpy())
    assert (bar_t[ev["gidx"].to_numpy()] == ev["t"].to_numpy()).all()
    ev["eidx"] = np.searchsorted(bar_t, (ev["day"].to_numpy() + 1) * DAY)
    sim = F.simulate(ev, df, rrs=(1.0, 2.0))
    for c in ("small", "large", "ctrl", "small_k3", "large_k3", "ctrl_k3") + tuple(f"small_{tf}" for tf in F.TFS):
        sim[c] = sim[c].astype(bool)
    sim["half"] = np.where(sim.day < F.H2_START_DAY, "H1", "H2")
    sim["gpct_1"] = sim["gross_1"] * sim["w_pct"]
    sim["fam1"] = sim.family.str.split("|").str[0]
    keep_cols = [c for c in sim.columns if c not in ("gidx", "eidx", "half", "fam1", "gpct_1")]
    print("simulated", len(sim), round(time.time() - t0), "s", flush=True)

    ALL = pd.Series(True, index=sim.index)
    cells, diffs = [], []
    # ---- primaries (verdict-bearing)
    imb, large = sim["small"], sim["large"]
    ctrl_only = sim["ctrl"] & ~sim["small"]
    h1m, h2m = sim.half == "H1", sim.half == "H2"
    cells += [cell_row("IMB: SMALL k2", "primary H1", sim, imb, 1.0), cell_row("NOIMB: no SMALL k2", "primary H1", sim, ~imb, 1.0),
              cell_row("LARGE k2", "primary H2", sim, large, 1.0), cell_row("NOLARGE: no LARGE k2", "primary H2", sim, ~large, 1.0)]
    d1 = diff_row("Delta1 = IMB - NOIMB", "primary H1", sim, imb, ~imb, 1.0)
    d2 = diff_row("Delta2 = LARGE - NOLARGE", "primary H2", sim, large, ~large, 1.0)
    diffs += [d1, d2]
    # ---- halves of the primaries
    hd = {}
    for hn, hm in (("H1", h1m), ("H2", h2m)):
        for tag, ma, mb in (("Delta1", imb, ~imb), ("Delta2", large, ~large)):
            r = diff_row(f"{tag} in {hn}", "halves", sim, ma & hm, mb & hm, 1.0)
            diffs.append(r)
            hd[(tag, hn)] = r["diff R"]
    # ---- sensitivity: SMALL and LARGE x k x rr (primaries excluded)
    for flag in ("small", "large"):
        for k, suf in K_COLS.items():
            for rr in (1.0, 2.0):
                if k == 2.0 and rr == 1.0:
                    continue
                flag_col = f"{flag}{suf}"
                m = sim[flag_col]
                nm = f"{flag.upper()} k{k:g} rr{rr:g}"
                cells.append(cell_row(nm, "sensitivity", sim, m, rr))
                diffs.append(diff_row(f"Delta {nm} vs rest", "sensitivity", sim, m, ~m, rr))
    # ---- control, per-TF, base, families
    for rr in (1.0, 2.0):
        cells.append(cell_row("CTRL only (shape, no volume)", "control", sim, ctrl_only, rr))
        cells.append(cell_row("ALL layer trades", "base", sim, ALL, rr))
    for tf in F.TFS:
        cells.append(cell_row(f"SMALL k2 on {tf} only", "per-TF", sim, sim[f"small_{tf}"], 1.0))
    for fam in sorted(sim.fam1.unique()):
        cells.append(cell_row(f"family {fam}", "family", sim, sim.fam1 == fam, 1.0))

    # ---- decisions (PRE_REG section 4)
    p_h = F.holm_p([d1["p"], d2["p"]], m=F.HOLM_M)
    s_imb = F.stats(sim.loc[imb, "net_1"].to_numpy(), sim.loc[imb, "day"].to_numpy())
    mean_ctrl = float(sim.loc[ctrl_only, "net_1"].mean()) if ctrl_only.any() else float("nan")
    in1 = dict(n_imb=int(imb.sum()), n_noimb=int((~imb).sum()), days_imb=int(sim.day[imb].nunique()), mean_imb=s_imb["mean"], t_imb=s_imb["t"],
               delta=d1["diff R"], p_holm=p_h[0], delta_h1=hd[("Delta1", "H1")], delta_h2=hd[("Delta1", "H2")], mean_ctrl=mean_ctrl, mde=d1["MDE R"])
    in2 = dict(n_large=int(large.sum()), delta=d2["diff R"], p_holm=p_h[1], delta_h1=hd[("Delta2", "H1")], delta_h2=hd[("Delta2", "H2")], mde=d2["MDE R"])
    v1, sub1 = F.decide_h1(in1)
    v2, sub2 = F.decide_h2(in2)
    study = "PASS" if "PASS" in (v1, v2) else ("FAIL" if (v1, v2) == ("FAIL", "FAIL") else "INCONCLUSIVE")

    # ---- verdict-arm table in the verdicts.py layout (mean G % of notional, SE day-clustered)
    def arm_row(label, mask, d, verdict, sub):
        g = sim[mask]
        s = F.stats(g["gpct_1"].to_numpy(), g["day"].to_numpy())
        nn = F.stats(g["net_1"].to_numpy(), g["day"].to_numpy())
        return {"arm": label, "n": s["n"], "mean G % (gross, of notional)": s["mean"], "SE G % (day-cl.)": s["se"], "net R": nn["mean"], "t_net": nn["t"],
                "Delta R vs rest": d["diff R"], "t_Delta": d["t"], "Holm p": d["p_holm"], "MDE R (2.8 SE)": d["MDE R"], "verdict": verdict}
    d1h, d2h = dict(d1, p_holm=p_h[0]), dict(d2, p_holm=p_h[1])
    arms = [arm_row("H1 filter: SMALL imbalance at the level (k2, rr1)", imb, d1h, v1, sub1),
            arm_row("H2 veto: LARGE imbalance at the level (k2, rr1)", large, d2h, v2, sub2)]
    cell_cols = ["cell", "block", "rr", "n", "days", "target %", "stop %", "time %", "gross R", "cost R", "net R", "SE", "t", "net R maker-in"]
    diff_cols = ["cell", "block", "rr", "n_a", "n_b", "diff R", "SE", "t", "p", "MDE R"]
    n_cells = len(cells) - 2 + len([r for r in diffs if r["block"] == "halves"])      # NOIMB / NOLARGE are complements, not declared cells
    pd.DataFrame([{"cell": r["cell"], "block": r["block"], "rr": r["rr"], "n": r["n"], "net_R": r["net R"], "se": r["SE"]} for r in cells]
                 + [{"cell": r["cell"], "block": r["block"], "rr": r["rr"], "n": r["n_a"], "net_R": r["diff R"], "se": r["SE"]} for r in diffs if r["block"] == "halves"]
                 ).to_csv(out / "trials.csv", index=False, lineterminator="\n", float_format="%.6g")

    base1 = next(r for r in cells if r["cell"] == "ALL layer trades" and r["rr"] == 1.0)
    base2 = next(r for r in cells if r["cell"] == "ALL layer trades" and r["rr"] == 2.0)
    imb_row, noimb_row = cells[0], cells[1]
    ctrl1 = next(r for r in cells if r['cell'].startswith('CTRL only') and r['rr'] == 1.0)
    lg_row, nolg_row = cells[2], cells[3]
    flag_share = f"SMALL k2 on {100 * imb.mean():.1f} % of trades, LARGE k2 on {100 * large.mean():.1f} %, CTRL-only on {100 * ctrl_only.mean():.1f} %"
    L = [study, "",
         f"# RESULT: Qriptal volume-anomaly candle as a filter and a veto on the lc-levels-hold level layer, BTCUSDT 1m, DEV only (generated by `run_filter.py run`)", "",
         f"**H1 filter: {v1}{(' (' + sub1 + ')') if sub1 else ''}. H2 veto: {v2}{(' (' + sub2 + ')') if sub2 else ''}.** Study word = {study} (PASS if either primary passes; FAIL only if both fail; otherwise INCONCLUSIVE). "
         "DEV only (bars before 2024-07-01, decisions 2022-04-01..2024-06-30); VALIDATION and HOLDOUT were not read. Rules frozen in PRE_REG.md (committed before this file); one run; nothing adopted.", "",
         "## Answer in numbers (fee-net R per trade, taker both legs 0.14 % round trip, 1R:1R bracket)", "",
         f"- The layer alone (all {base1['n']} first-touch fades of the 8 KEEP families): net **{base1['net R']:+.3f} R** per trade at rr 1 (gross {base1['gross R']:+.3f}, cost {base1['cost R']:.3f}), "
         f"**{base2['net R']:+.3f} R** at rr 2.",
         f"- WITH a volume-anomaly small-body candle at the level (IMB, n {imb_row['n']}): net **{imb_row['net R']:+.3f} R** (SE {imb_row['SE']:.3f}, t {imb_row['t']:+.2f}); "
         f"WITHOUT (n {noimb_row['n']}): **{noimb_row['net R']:+.3f} R**. Difference {d1['diff R']:+.3f} R (SE {d1['SE']:.3f}, t {d1['t']:+.2f}, Holm p {p_h[0]:.3f}); "
         f"shape-only control (n {ctrl1['n']}): {ctrl1['net R']:+.3f} R.",
         f"- Large-body veto: trades with a high-volume LARGE-body candle at the level (n {lg_row['n']}) net **{lg_row['net R']:+.3f} R** vs {nolg_row['net R']:+.3f} R for the rest; "
         f"difference {d2['diff R']:+.3f} R (SE {d2['SE']:.3f}, t {d2['t']:+.2f}, Holm p {p_h[1]:.3f}). Removing them changes the layer from {base1['net R']:+.3f} to {nolg_row['net R']:+.3f} R.",
         f"- Flag coverage: {flag_share}.", "",
         "## Verdict arms (primary cells; mean G % = gross R x width %, SE day-clustered; verdict rule in PRE_REG.md section 4)", "",
         md_table(arms, list(arms[0].keys()), {"mean G % (gross, of notional)": "{:.4f}", "SE G % (day-cl.)": "{:.4f}", "net R": "{:+.4f}", "t_net": "{:+.2f}",
                                                "Delta R vs rest": "{:+.4f}", "t_Delta": "{:+.2f}", "Holm p": "{:.4f}", "MDE R (2.8 SE)": "{:.3f}"}), "",
         "Decision inputs (H1): " + ", ".join(f"{k}={v:.4g}" if isinstance(v, float) else f"{k}={v}" for k, v in in1.items()) + ".",
         "Decision inputs (H2): " + ", ".join(f"{k}={v:.4g}" if isinstance(v, float) else f"{k}={v}" for k, v in in2.items()) + ".", "",
         f"## Cells: outcome of each group (net R after fees; {len(cells)} group cells)", "",
         md_table(cells, cell_cols, {"rr": "{:g}", "target %": "{:.1f}", "stop %": "{:.1f}", "time %": "{:.1f}", "gross R": "{:+.3f}", "cost R": "{:.3f}", "net R": "{:+.3f}",
                                      "SE": "{:.3f}", "t": "{:+.2f}", "net R maker-in": "{:+.3f}"}), "",
         "## Differences (group minus rest, same days share covariance; two-sided normal p, unadjusted unless named Holm above)", "",
         md_table(diffs, diff_cols, {"rr": "{:g}", "diff R": "{:+.3f}", "SE": "{:.3f}", "t": "{:+.2f}", "p": "{:.4f}", "MDE R": "{:.3f}"}), "",
         f"## Declared trial count: {n_cells} outcome cells (PRE_REG section 5 declared 28), 2 verdict-bearing", "",
         f"Computed here: {len(cells) - 2} group cells (the two complements NOIMB / NOLARGE are not counted) + {len([r for r in diffs if r['block'] == 'halves'])} half-difference cells = {n_cells}; `trials.csv` lists them. Holm m = {F.HOLM_M} (14 variants read earlier on DEV + 2 primaries).",
         "The maker-in column is a cost readout only and never rescues a verdict.", "",
         "## Parameter labels", "",
         "SOURCED: taker 5 bp / maker 2 bp per side (`backtest/fees.py:27-28`); Qriptal's qualitative rule (quotes with file:line in PRE_REG.md section 3); the 8 KEEP families (`levels_hold.md`, LC1); DEV split (`dsa_backtest_audit_2026-10-16/AUDIT_BRIEF.md:16`).",
         "OURS (fixed in PRE_REG.md before the run): k 2 (3 sensitivity), body 0.30 / 0.70, 50-bar median volume, TFs 1h/4h/12h/1d, windows 7/14/30/60 days, midpoint tolerance 0.25 %, "
         "width max(0.4 % of day open, 0.1 % of level), target 1R (2R secondary), touch fill at the level, 2 bp slippage per leg, dedup, time exit 23:59 UTC, warmup to 2022-04-01, halves split 2023-04-01, Holm m 16, MDE bar 0.15 R.", ""]
    sim[keep_cols].to_csv(out / "trades_dev.csv", index=False, lineterminator="\n", float_format="%.8g")
    write(out, "RESULT.md", "\n".join(L))
    print(study, v1, sub1, v2, sub2, "cells", n_cells, round(time.time() - t0), "s", flush=True)


if __name__ == "__main__":
    {"counts": counts, "run": run}[sys.argv[1]]()
