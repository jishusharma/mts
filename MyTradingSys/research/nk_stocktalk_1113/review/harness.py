"""NK StockTalk review harness: build the per-concept checklist and check Hindi quotes against the caption.

Usage (repo root):
    python MyTradingSys/research/nk_stocktalk_1113/review/harness.py fill   # writes CHECKLIST.md from both extracts
    python MyTradingSys/research/nk_stocktalk_1113/review/harness.py check  # every quote vs its Hindi caption; exit 1 on a miss

Why a separate check: scripts/dev/verify_extract_quotes.py norm() keeps only [a-z0-9%], so every Devanagari
word is dropped (pure-Hindi quote = always MISSING; mixed quote = only its Latin words compared).
This check keeps Unicode letters, marks and digits (NFC), so Hindi words are compared too.
"""
import json
from itertools import islice
import re
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
CONCEPTS = json.loads((HERE / "concepts.json").read_text(encoding="utf-8"))
MODELS = ("flash", "argon")
QUOTE = re.compile(r'^>\s*"(.*)"\s*$')
GPS = re.compile(r"Source GPS:\s*([A-Za-z0-9_-]{11})")
TS = re.compile(r"\[\d+:\d{2}(?::\d{2})?\]")
TRANS = re.compile(r"^\s*(?:[-*]\s*)?\**TRANSLATION\**\s*:?\**\s*(.*)$", re.I)


def norm(s):
    s = unicodedata.normalize("NFC", TS.sub(" ", s)).lower()
    keep = "".join(ch if unicodedata.category(ch)[0] in "LMN" or ch == "%" else " " for ch in s)
    return " ".join(keep.split())


def caption(vid):
    p = ROOT / "raw_transcripts_canonical" / f"{vid}_raw.txt"
    return p.read_text(encoding="utf-8", errors="replace") if p.is_file() else None


def quotes(model, vid):
    """[(line, quote, translation)] from <model>/<vid>/EXTRACT.md; [] when the extract is not there."""
    p = HERE.parent / model / vid / "EXTRACT.md"
    if not p.is_file():
        return []
    lines = p.read_text(encoding="utf-8").splitlines()
    out = []
    for i, line in enumerate(lines):
        m = QUOTE.match(line.strip())
        if not m:
            continue
        near = list(islice(lines, i + 1, i + 6))  # the 5 text lines under the quote
        gps = next((GPS.search(x).group(1) for x in near if GPS.search(x)), vid)
        tr = next((TRANS.match(x).group(1).strip() for x in near if TRANS.match(x)), "")
        out.append((i + 1, m.group(1), tr, gps))
    return out


def check():
    bad = total = 0
    for c in CONCEPTS:
        for model in MODELS:
            for ln, q, _, vid in quotes(model, c["video"]):
                total += 1
                body = caption(vid)
                nq = norm(q)
                if body is None:
                    verdict = "NO-CAPTION"
                elif not nq:
                    verdict = "EMPTY"
                elif all(f" {norm(f)} " in f" {norm(body)} " for f in re.split(r"\.{3}|…", q) if norm(f)):
                    verdict = "OK"
                else:
                    verdict = "MISSING"
                bad += verdict != "OK"
                print(f"{verdict:10} {model}/{c['video']}/EXTRACT.md:{ln} {q[:50]!r}")
    print(f"hindi-check: {total} quotes, {bad} not OK" if total else "hindi-check: no extracts yet")
    return 1 if bad or not total else 0


def fill():
    out = ["# NK StockTalk review checklist (generated by harness.py fill; do not hand-edit)", ""]
    for c in CONCEPTS:
        out += [f"## {c['id']}: {c['name']} (video {c['video']})", "",
                f"Claim on the page: {c['rule']}", "",
                "| Param | Page value | Label | Reviewer: caption says |", "|---|---|---|---|"]
        out += [f"| {n} | {v} | {lab} | |" for n, v, lab in c["params"]]
        out += ["", "| Model | Line | Hindi quote (caption) | English rendering | Reviewer verdict |", "|---|---|---|---|---|"]
        rows = [(m, ln, q, tr) for m in MODELS for ln, q, tr, _ in quotes(m, c["video"])]
        out += [f"| {m} | {ln} | {q} | {tr or 'NO TRANSLATION LINE'} | |" for m, ln, q, tr in rows] or \
               ["| - | - | PENDING: extract not landed | - | |"]
        out.append("")
    (HERE / "CHECKLIST.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {HERE / 'CHECKLIST.md'}")
    return 0


if __name__ == "__main__":
    sys.exit({"fill": fill, "check": check}[sys.argv[1] if len(sys.argv) > 1 else "check"]())
