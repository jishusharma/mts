"""Card 3/4 btc-of-map-prints-1112: A1 large aggressor prints and A2 absorption, DEV only (PREREG.md frozen, not changed).
Definitions are PREREG's; choices not fixed there are labelled OURS.
- Sample (OURS, card): 6 blocks of 10 consecutive DEV event days, evenly spread, each preceded by 37 warm-up days (7 for the print
  threshold + 30 for the |L| distribution). Only the 60 event days are scored. No VALIDATION/GAP/RESERVE/HOLDOUT file is opened:
  the kline loader takes months 2022-01..2024-05 only and every event day is checked to be inside DEV 2022-02-01..2024-05-31.
- aggTrades (A1): one UTC day at a time from data.binance.vision into F:/MTS/Scratch/aggTrades_1112 (never C:), reduced to the top
  3 % of prints by quantity (5m bin, side, qty) plus the trade count, then the csv is deleted. Raw trades are never committed.
  Print threshold = quantity at descending rank floor(0.001 * N) of the pooled previous 7 full UTC days (99.9th pct, OURS rank
  rule); a print counts if qty >= threshold. If the threshold falls below a day's smallest stored qty that day is flagged truncated.
- A1: per 5m bar L = sum(qty buyer-aggressor prints >= thr) - sum(seller-aggressor prints >= thr), thr from the previous 7 full days.
  Event = |L| >= 98th pct of |L| over the 30 full UTC days before the bar's day (fixed per day, OURS; zeros included) and |L| > 0
  (OURS guard so an all-zero window cannot flag every bar). Long if L > 0.
- A2: delta5 = sum over five 1m bars of (2*taker_buy - volume). Event = |delta5| >= 98th pct of |delta5| over the previous 30 full UTC
  days (klines, per-day window, OURS) AND |c-o|/o < 0.1 % for the 5m bar. Long if delta5 < 0 (against the delta).
- Entry = open of the 1m bar right after the 5m event bar closes; forward return = close of the 1m bar 15 / 60 min later; net = gross -
  10 bp round trip (short: -gross - 10). Events with any missing 1m bar from the event bar to the end of the 60 min window are dropped.
- De-clustering: accept an event only if >= 60 min after the previous accepted one (same set for both horizons).
- Placebo (PREREG): 1,000 draws (seed 1112) of as many entry bars as accepted events, uniform over the sampled event-day 5m bars with the same
  UTC-hour histogram, same long/short count, same de-clustering; report mean, 1st and 99th percentile; z = (obs-placebo mean)/placebo sd.
- Regime (OURS, same as clocks.py): trailing 90 daily-close return > +20 % bull, < -20 % bear, else range.
"""
import argparse
import datetime as dt
import json
import os
import shutil
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, '..', '..', 'backtest'))

GRID0 = dt.date(2022, 1, 1)
DEV_START, DEV_END = dt.date(2022, 2, 1), dt.date(2024, 5, 31)
FIRST_EVENT = dt.date(2022, 2, 8)  # first block start: 37 warm-up days land on/after 2022-01-02
N_BLOCKS, BLOCK_LEN, WARM = 6, 10, 37
FEE_BP, SEED, NPERM = 10.0, 1112, 1000
SCRATCH = 'F:/MTS/Scratch/aggTrades_1112'
REDUCED = 'F:/MTS/Scratch/of_prints_1112_reduced'  # small derived files, regenerated by this script, never committed
MIN_FREE_GB, SCRATCH_CAP_GB = 20.0, 2.0
KEEP_FRAC = 0.03
DAY_MIN, BAR = 1440, 5
GAP_BARS = 12  # 60 min


# ---------------------------------------------------------------- days
def block_starts():
    last = DEV_END - dt.timedelta(days=BLOCK_LEN - 1)
    step = (last - FIRST_EVENT).days / (N_BLOCKS - 1)
    return [FIRST_EVENT + dt.timedelta(days=int(round(i * step))) for i in range(N_BLOCKS)]


def day_plan():
    """List of (date, block, role) with role 'warmup' or 'event'."""
    out = []
    for b, s in enumerate(block_starts()):
        for k in range(-WARM, BLOCK_LEN):
            out.append((s + dt.timedelta(days=k), b, 'warmup' if k < 0 else 'event'))
    return out


def write_days(path):
    with open(path, 'w') as fh:
        fh.write('# date block role  (DEV sample: 6 blocks x 10 consecutive event days + 37 warm-up days each; OURS, see prints.py)\n')
        for d, b, r in day_plan():
            fh.write('%s %d %s\n' % (d.isoformat(), b, r))


def read_days(path):
    out = []
    with open(path) as fh:
        for ln in fh:
            if ln.strip() and not ln.startswith('#'):
                d, b, r = ln.split()
                out.append((dt.date.fromisoformat(d), int(b), r))
    return out


def gidx(d):
    return (d - GRID0).days


# ---------------------------------------------------------------- aggTrades reduction
def reduce_day(ts_ms, qty, is_buyer_maker, day):
    """Reduce one UTC day of aggTrades. Returns dict n, bin (int16), side (int8, +1 buyer aggressor), qty (float64) of the top KEEP_FRAC."""
    n = len(qty)
    if n == 0:
        return dict(n=0, bin=np.zeros(0, np.int16), side=np.zeros(0, np.int8), qty=np.zeros(0))
    t0 = int(np.datetime64(day.isoformat() + 'T00:00', 'ms').astype('int64'))
    k = max(1, int(np.ceil(KEEP_FRAC * n)))
    order = np.argsort(-qty, kind='stable')[:k]
    b = ((np.asarray(ts_ms)[order] - t0) // (BAR * 60000)).astype(np.int16)
    side = np.where(np.asarray(is_buyer_maker)[order], -1, 1).astype(np.int8)
    return dict(n=int(n), bin=b, side=side, qty=np.asarray(qty, float)[order])


def print_threshold(prev):
    """99.9th percentile of the pooled previous days (rank rule, OURS). prev = list of reduced dicts. Returns (thr, truncated_flag)."""
    n = sum(r['n'] for r in prev)
    if n == 0:
        return None, False
    q = np.sort(np.concatenate([r['qty'] for r in prev]))[::-1]
    thr = float(q[min(int(0.001 * n), len(q) - 1)])
    trunc = any(len(r['qty']) and r['qty'].min() > thr for r in prev)
    return thr, trunc


def day_L(red, thr):
    """L per 5m bin (288) for one day given its threshold."""
    L = np.zeros(DAY_MIN // BAR)
    m = red['qty'] >= thr
    np.add.at(L, red['bin'][m].astype(int), red['side'][m] * red['qty'][m])
    return L


def a1_day_events(L_prev30, L_today):
    """Bool mask over the day's 5m bars: |L| >= p98 of previous 30 days' |L| and |L| > 0."""
    p98 = np.percentile(np.abs(L_prev30), 98)
    a = np.abs(L_today)
    return (a >= p98) & (a > 0)


# ---------------------------------------------------------------- minute grid
def five(x, fn):
    return fn(x.reshape(-1, BAR), axis=1)


def delta5_and_move(o, c, v, tb):
    n = len(o) // BAR * BAR
    d1 = 2 * tb[:n] - v[:n]
    d5 = d1.reshape(-1, BAR).sum(1)
    o5 = o[:n].reshape(-1, BAR)[:, 0]
    c5 = c[:n].reshape(-1, BAR)[:, -1]
    mv = np.abs(c5 / o5 - 1)
    return d5, mv


def a2_day_events(d5_prev30, d5_today, mv_today):
    x = np.abs(d5_prev30)
    x = x[np.isfinite(x)]
    if len(x) == 0:
        return np.zeros(len(d5_today), bool)
    p98 = np.percentile(x, 98)
    with np.errstate(invalid='ignore'):
        return (np.abs(d5_today) >= p98) & (mv_today < 0.001)


def gross_arrays(o, c):
    """Per 5m bar: gross forward bp (long) at 15 and 60 min from the next 1m open; NaN if any 1m bar missing from bar start to window end."""
    nb = len(o) // BAR
    bad = ~(np.isfinite(o) & np.isfinite(c))
    cs = np.concatenate([[0], np.cumsum(bad)])
    out = np.full((2, nb), np.nan)
    for k, h in enumerate((15, 60)):
        for g in range(nb):
            m = g * BAR
            e, j = m + BAR, m + BAR + h - 1
            if j >= len(o) or cs[j + 1] - cs[m] > 0:
                continue
            out[k, g] = (c[j] / o[e] - 1) * 1e4
    return out


def decluster(bars, gap=GAP_BARS):
    out, last = [], None
    for b in sorted(bars):
        if last is None or b - last >= gap:
            out.append(b)
            last = b
    return out


def stats(net):
    net = np.asarray(net, float)
    n = len(net)
    if n < 2:
        return dict(n=n, mean=float('nan'), sd=float('nan'), t=float('nan'), pos=float('nan'))
    sd = net.std(ddof=1)
    return dict(n=n, mean=float(net.mean()), sd=float(sd), t=float(net.mean() / (sd / np.sqrt(n))) if sd > 0 else float('nan'),
                pos=float((net > 0).mean()))


def placebo(pool_bars, hours, gross, n_long, n_short, nperm=NPERM, seed=SEED):
    """Placebo means (nperm x 2 horizons). pool_bars: candidate 5m bar indices; hours: UTC hour of each accepted event (same histogram)."""
    rng = np.random.default_rng(seed)
    pool_bars = np.asarray(pool_bars)
    ph = (pool_bars % 288) // 12
    byh = {h: pool_bars[ph == h] for h in range(24)}
    hist = np.bincount(np.asarray(hours, int), minlength=24)
    res = np.full((nperm, 2), np.nan)
    n = int(hist.sum())
    if n == 0:
        return res
    for i in range(nperm):
        draw = []
        for h in range(24):
            if hist[h] and len(byh[h]):
                draw.extend(rng.choice(byh[h], hist[h], replace=True))
        draw = np.array(draw)
        sign = np.array([1] * n_long + [-1] * n_short)[:len(draw)]
        rng.shuffle(sign)
        order = np.argsort(draw, kind='stable')
        acc, last = [], None
        for j in order:
            if last is None or draw[j] - last >= GAP_BARS:
                acc.append(j)
                last = draw[j]
        for k in range(2):
            g = gross[k, draw[acc]]
            res[i, k] = np.mean(sign[acc] * g - FEE_BP)
    return res


# ---------------------------------------------------------------- fetch and reduce
def free_gb(path='F:/'):
    return shutil.disk_usage(path).free / 1e9


def dir_gb(path):
    tot = 0
    for r, _, fs in os.walk(path):
        for f in fs:
            tot += os.path.getsize(os.path.join(r, f))
    return tot / 1e9


def fetch_and_reduce(day, log):
    """Fetch one day, reduce, delete scratch. Returns 'ok' / 'skip' / reason string (goes to NOT_IN_DATA)."""
    import pandas as pd
    import fetch_binance_archive as fb
    out = os.path.join(REDUCED, day.isoformat() + '.npz')
    if os.path.exists(out):
        return 'skip'
    fg = free_gb()
    if fg < MIN_FREE_GB:
        return 'F: free %.1f GB < %.0f GB' % (fg, MIN_FREE_GB)
    os.makedirs(SCRATCH, exist_ok=True)
    os.makedirs(REDUCED, exist_ok=True)
    from pathlib import Path
    try:
        st = fb.fetch_one('aggTrades', 'daily', day.isoformat(), Path(SCRATCH))
    except Exception as e:  # noqa: BLE001
        shutil.rmtree(SCRATCH, ignore_errors=True)
        return 'fetch error: %s' % e
    try:
        if st not in ('ok', 'skip'):
            return 'archive status %s' % st
        if dir_gb(SCRATCH) > SCRATCH_CAP_GB:
            return 'scratch > %.0f GB cap' % SCRATCH_CAP_GB
        f = os.path.join(SCRATCH, 'BTCUSDT-aggTrades-%s.csv' % day.isoformat())
        df = pd.read_csv(f, usecols=['transact_time', 'quantity', 'is_buyer_maker'], dtype={'quantity': 'float64'})
        ibm = df['is_buyer_maker'].astype(str).str.lower().eq('true').to_numpy()
        red = reduce_day(df['transact_time'].to_numpy(), df['quantity'].to_numpy(), ibm, day)
        np.savez_compressed(out, **red)
        del df
        return 'ok'
    finally:
        shutil.rmtree(SCRATCH, ignore_errors=True)
        os.makedirs(SCRATCH, exist_ok=True)


def load_reduced(day):
    p = os.path.join(REDUCED, day.isoformat() + '.npz')
    if not os.path.exists(p):
        return None
    z = np.load(p)
    return dict(n=int(z['n']), bin=z['bin'], side=z['side'], qty=z['qty'])


# ---------------------------------------------------------------- analysis
def a1_events_from_reduced(red_by_day, event_days):
    """red_by_day: {date: reduced}. Returns (events[(global 5m bar, sign)], flags list of truncated dates, dropped_days)."""
    L_cache, thr_cache, trunc, dropped = {}, {}, [], []

    def L_of(d):
        if d in L_cache:
            return L_cache[d]
        prev = [red_by_day.get(d - dt.timedelta(days=k)) for k in range(1, 8)]
        if red_by_day.get(d) is None or any(p is None for p in prev):
            L_cache[d] = None
            return None
        thr, tr = print_threshold(prev)
        if tr:
            trunc.append(d)
        thr_cache[d] = thr
        L_cache[d] = day_L(red_by_day[d], thr)
        return L_cache[d]

    ev = []
    for d in event_days:
        L = L_of(d)
        prev30 = [L_of(d - dt.timedelta(days=k)) for k in range(1, 31)]
        if L is None or any(p is None for p in prev30):
            dropped.append(d)
            continue
        m = a1_day_events(np.concatenate(prev30), L)
        for b in np.nonzero(m)[0]:
            ev.append((gidx(d) * 288 + int(b), 1 if L[b] > 0 else -1))
    return ev, trunc, dropped


def a2_events(d5, mv, event_days):
    ev = []
    for d in event_days:
        g = gidx(d)
        prev = d5[(g - 30) * 288:g * 288]
        m = a2_day_events(prev, d5[g * 288:(g + 1) * 288], mv[g * 288:(g + 1) * 288])
        for b in np.nonzero(m)[0]:
            ev.append((g * 288 + int(b), -1 if d5[g * 288 + b] > 0 else 1))
    return ev


def accept(ev, gross):
    """De-cluster events in time order, drop those without both forward returns. Returns list of (bar, sign)."""
    ev = sorted(ev)
    ok = [(b, s) for b, s in ev if np.isfinite(gross[:, b]).all()]
    keep = set(decluster([b for b, _ in ok]))
    return [(b, s) for b, s in ok if b in keep]


def session(h):
    return 'Asia' if h < 8 else 'Europe' if h < 14 else 'US' if h < 21 else 'Late'


def regime_of_day(c, d):
    j, j0 = gidx(d) * DAY_MIN + DAY_MIN - 1, (gidx(d) - 90) * DAY_MIN + DAY_MIN - 1
    if j0 < 0 or j >= len(c) or not (np.isfinite(c[j]) and np.isfinite(c[j0])):
        return 'n/a'
    r = c[j] / c[j0] - 1
    return 'bull' if r > .2 else 'bear' if r < -.2 else 'range'


def cell_report(name, acc, gross, pool_bars, c):
    bars = np.array([b for b, _ in acc], int)
    sign = np.array([s for _, s in acc], int)
    n = len(acc)
    rep = dict(event=name, n=n, n_long=int((sign > 0).sum()), n_short=int((sign < 0).sum()))
    hours = (bars % 288) // 12
    plc = placebo(pool_bars, hours, gross, rep['n_long'], rep['n_short']) if n else np.full((NPERM, 2), np.nan)
    for k, h in enumerate((15, 60)):
        net = sign * gross[k, bars] - FEE_BP if n else np.array([])
        st = stats(net)
        pm, ps = np.nanmean(plc[:, k]), np.nanstd(plc[:, k])
        rep['h%d' % h] = dict(**st, gross_mean=float((sign * gross[k, bars]).mean()) if n else float('nan'),
                              placebo_mean=float(pm), placebo_p1=float(np.nanpercentile(plc[:, k], 1)) if n else float('nan'),
                              placebo_p99=float(np.nanpercentile(plc[:, k], 99)) if n else float('nan'),
                              z=float((st['mean'] - pm) / ps) if ps and np.isfinite(ps) else float('nan'))
    ses = {}
    for s in ('Asia', 'Europe', 'US', 'Late'):
        m = np.array([session(h) == s for h in hours], bool) if n else np.array([], bool)
        ses[s] = dict(n=int(m.sum()), net60=float((sign[m] * gross[1, bars[m]] - FEE_BP).mean()) if m.any() else float('nan'))
    rep['session'] = ses
    reg = {}
    days = [GRID0 + dt.timedelta(days=int(b // 288)) for b in bars]
    rg = np.array([regime_of_day(c, d) for d in days]) if n else np.array([])
    for r in ('bull', 'bear', 'range', 'n/a'):
        m = rg == r if n else np.array([], bool)
        reg[r] = dict(n=int(m.sum()), net60=float((sign[m] * gross[1, bars[m]] - FEE_BP).mean()) if m.any() else float('nan'))
    rep['regime'] = reg
    rep['insufficient_n'] = n < 180
    return rep


def mark(rep):
    r = []
    for h in ('h15', 'h60'):
        x = rep[h]
        if rep['insufficient_n']:
            r.append('INSUFFICIENT_N')
        elif x['t'] >= 2.64 and x['mean'] > 0:
            r.append('DEV-clears-LEAD-bar(VALIDATION not run)')
        elif x['mean'] <= 0 and x['gross_mean'] > FEE_BP * 0 and x['gross_mean'] > 0:
            r.append('gross only')
        else:
            r.append('none')
    return r


def f(x, fmt='%+.2f'):
    return 'n/a' if x is None or not np.isfinite(x) else fmt % x


def render(reps, meta):
    L = ['# PRINTS: BTC large prints (A1) and absorption (A2), card btc-of-map-prints-1112, DEV sample only', '',
         'Frozen definitions: PREREG.md (not changed). Sample: %d event days = %d blocks x %d consecutive days (+%d warm-up days each; OURS, card). '
         'DEV only: VALIDATION, GAP, RESERVE, HOLDOUT never opened; cells are therefore marked from DEV alone and no PASS/LEAD is possible.' % (
             meta['event_days'], N_BLOCKS, BLOCK_LEN, WARM),
         'Net = gross forward bp minus 10 bp round trip, entry next 1m open after the 5m event bar, 60 min de-clustering. '
         'Control = PREREG placebo (1,000 draws, seed 1112, hour-matched, same long/short count, same de-clustering) on the same sampled days; '
         'z = (obs - control mean) / control sd; t = mean/(sd/sqrt(n)).', '',
         '| Event | n | fwd 15m net bp | control 15m (p1..p99) | z15 | t15 | fwd 60m net bp | control 60m (p1..p99) | z60 | t60 | gross 60m bp | mark 15m / 60m |',
         '|---|---|---|---|---|---|---|---|---|---|---|---|']
    for r in reps:
        a, b = r['h15'], r['h60']
        L.append('| %s | %d (L %d / S %d) | %s | %s (%s..%s) | %s | %s | %s | %s (%s..%s) | %s | %s | %s | %s |' % (
            r['event'], r['n'], r['n_long'], r['n_short'], f(a['mean']), f(a['placebo_mean']), f(a['placebo_p1']), f(a['placebo_p99']),
            f(a['z']), f(a['t']), f(b['mean']), f(b['placebo_mean']), f(b['placebo_p1']), f(b['placebo_p99']), f(b['z']), f(b['t']),
            f(b['gross_mean']), ' / '.join(mark(r))))
    L += ['', 'Minimum n (PREREG): DEV n >= 180 per cell; below that the cell is INSUFFICIENT_N and gets no verdict. The 60-day sample is a sample of DEV, '
          'not all of it, so a low n here is a sampling limit, not a statement about the full DEV window.', '']
    for r in reps:
        L.append('**%s by session (n / net60 bp):** ' % r['event'] + ', '.join('%s %d / %s' % (k, v['n'], f(v['net60'])) for k, v in r['session'].items()))
        L.append('**%s by regime (n / net60 bp):** ' % r['event'] + ', '.join('%s %d / %s' % (k, v['n'], f(v['net60'])) for k, v in r['regime'].items()))
    rc = meta['regime_mix']
    tot = max(sum(rc.values()), 1)
    L += ['', 'Regime mix: ' + ', '.join('%s %.0f%%' % (k, 100 * v / tot) for k, v in rc.items()) + ' of %d sampled event days (DEV).' % tot, '',
          'A1 data: %d event days used, %d dropped for missing aggTrades windows, %d days flagged truncated (threshold below a day\'s stored top %d%%). '
          'A1 events from aggTrades; A2 from 1m klines with taker delta.' % (meta['a1_days_used'], meta['a1_days_dropped'], meta['a1_trunc'], int(KEEP_FRAC * 100)),
          'Missing days are listed in NOT_IN_DATA.md when any.']
    return '\n'.join(L) + '\n'


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--days', required=True)
    ap.add_argument('--analyze-only', action='store_true')
    ap.add_argument('--klines', default=None)
    a = ap.parse_args(argv)
    days = read_days(a.days)
    for d, _, r in days:
        if r == 'event' and not (DEV_START <= d <= DEV_END):
            raise SystemExit('event day %s outside DEV: refused' % d)
    missing = {}
    if not a.analyze_only:
        for i, (d, b, r) in enumerate(days):
            st = fetch_and_reduce(d, None)
            if st not in ('ok', 'skip'):
                missing[d.isoformat()] = st
            print('%d/%d %s %s %s' % (i + 1, len(days), d, r, st), flush=True)
    red = {d: load_reduced(d) for d, _, _ in days}
    for d, v in red.items():
        if v is None and d.isoformat() not in missing:
            missing[d.isoformat()] = 'not fetched (analyze-only or earlier failure)'
    import clocks
    t0, o, c, v, tb = clocks.load_dev(**({'pattern': a.klines} if a.klines else {}))
    ev_days = [d for d, _, r in days if r == 'event']
    d5, mv = delta5_and_move(o, c, v, tb)
    gross = gross_arrays(o, c)
    pool = [gidx(d) * 288 + b for d in ev_days for b in range(288) if np.isfinite(gross[:, gidx(d) * 288 + b]).all()]
    ev1, trunc, dropped = a1_events_from_reduced(red, ev_days)
    acc1 = accept(ev1, gross)
    acc2 = accept(a2_events(d5, mv, ev_days), gross)
    reps = [cell_report('A1 large print (with L)', acc1, gross, pool, c), cell_report('A2 absorption (against delta)', acc2, gross, pool, c)]
    rc = {'bull': 0, 'bear': 0, 'range': 0, 'n/a': 0}
    for d in ev_days:
        rc[regime_of_day(c, d)] += 1
    meta = dict(event_days=len(ev_days), regime_mix=rc, a1_days_used=len(ev_days) - len(dropped), a1_days_dropped=len(dropped), a1_trunc=len(set(trunc)))
    with open(os.path.join(HERE, 'PRINTS.md'), 'w') as fh:
        fh.write(render(reps, meta))
    with open(os.path.join(HERE, 'results_prints.json'), 'w') as fh:
        json.dump(dict(meta=meta, cells=reps), fh, indent=1, default=float)
    nid = os.path.join(HERE, 'NOT_IN_DATA.md')
    if missing:
        with open(nid, 'w') as fh:
            fh.write('# NOT_IN_DATA: aggTrades days not fetched (card btc-of-map-prints-1112)\n\n| Day | Reason |\n|---|---|\n')
            for k in sorted(missing):
                fh.write('| %s | %s |\n' % (k, missing[k]))
    elif os.path.exists(nid):
        os.remove(nid)
    print('A1 n=%d A2 n=%d missing=%d' % (len(acc1), len(acc2), len(missing)))


if __name__ == '__main__':
    main()
