"""Rank the extraction backlog (GAPS.md) so order-flow content is read first. No network.

ON_DISK  = "Transcript but no extract" ids, title/analyst from raw_transcripts_canonical headers.
TO_FETCH = "Priority id with no transcript" ids, title from video_priority_2026-10-15/RANKED_*.csv.
Score = count of order-flow keywords in title (+ first 200 body lines for ON_DISK). Keyword list is OURS.
Ties: Tom and Fabio first, then id. Ids with no title go to NO_TITLE, never guessed.
"""
import csv
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
KEYWORDS = ["delta", "absorption", "forced", "liquidation", "auction", "footprint"]  # OURS
FIRST = ("tom", "fabio")
SEC_ON, SEC_FETCH = "Transcript but no extract", "Priority id with no transcript"


def score(text):
    low = text.lower()
    return sum(len(re.findall(re.escape(k), low)) for k in KEYWORDS)


def gap_ids(gaps_text, name):
    m = re.search(r"^## " + re.escape(name) + r" \((\d+)\)\n(.*?)(?=^## |\Z)", gaps_text, re.S | re.M)
    ids = re.findall(r"^- (\S+)\s*$", m.group(2), re.M) if m else []
    return ids


def find_transcript(tdir, vid):
    for suf in ("_raw.txt", "_hi_raw.txt", "_asr_raw.txt"):
        p = tdir / f"{vid}{suf}"
        if p.exists():
            return p
    return None


def fix_mojibake(t):
    for enc in ("cp1252", "cp1251"):
        try:
            return t.encode(enc).decode("utf-8")
        except (UnicodeEncodeError, UnicodeDecodeError):
            pass
    return t


def header(p):
    """(title, analyst, body_text) from a canonical transcript; header lines start with '#'."""
    title, analyst, source, body = "", "", "", []
    with p.open(encoding="utf-8", errors="replace") as f:
        for i, line in enumerate(f):
            if line.startswith("# Title:") and not title:
                title = fix_mojibake(line[8:].strip())
            elif line.startswith("# Analyst:") and not analyst:
                analyst = line[10:].strip()
            elif line.startswith("# Source:") and not source:
                source = line.lower()
            elif not line.startswith("#"):
                body.append(line)
            if i >= 200:
                break
    if not analyst:  # fall back to the capture folder named in the Source line
        analyst = next((n.title() for n in FIRST if n in source), "")
    return title, analyst, "".join(body)


def priority_titles(root):
    out = {}
    d = root / "MyTradingSys" / "research" / "video_priority_2026-10-15"
    for p in sorted(d.glob("RANKED_*.csv")) if d.exists() else []:
        with p.open(encoding="utf-8", newline="") as f:
            for r in csv.DictReader(f):
                if r.get("id"):
                    out[r["id"]] = (r.get("english_title") or r.get("title") or "", r.get("channel", ""))
    return out


def ledger_channels(ledger):
    out = {}
    if ledger.exists():
        with ledger.open(encoding="utf-8", newline="") as f:
            for r in csv.DictReader(f):
                if r["channel"]:
                    out.setdefault(r["video_id"], r["channel"])
    return out


def transcript_dir(root):
    d = root / "raw_transcripts_canonical"
    if d.exists():
        return d
    try:  # git-ignored: a worktree reads the main checkout
        common = subprocess.run(["git", "-C", str(root), "rev-parse", "--git-common-dir"], capture_output=True,
                                text=True, check=True).stdout.strip()
        alt = (root / common).resolve().parent / "raw_transcripts_canonical"
        if alt.exists():
            return alt
    except Exception:
        pass
    return d


def order_key(r):
    return (-r["score"], 0 if any(n in r["analyst"].lower() for n in FIRST) else 1, r["id"])


def build(gaps_text, tdir, prio, chans):
    on, fetch, no_title = [], [], []
    for vid in gap_ids(gaps_text, SEC_ON):
        p = find_transcript(tdir, vid)
        title, analyst, body = header(p) if p else ("", "", "")
        if not title:
            no_title.append((vid, "ON_DISK"))
            continue
        on.append({"id": vid, "analyst": analyst or chans.get(vid, ""), "title": title, "score": score(title + "\n" + body)})
    for vid in gap_ids(gaps_text, SEC_FETCH):
        title, ch = prio.get(vid, ("", ""))
        if not title:
            no_title.append((vid, "TO_FETCH"))
            continue
        fetch.append({"id": vid, "analyst": ch or chans.get(vid, ""), "title": title, "score": score(title)})
    return sorted(on, key=order_key), sorted(fetch, key=order_key), no_title


def cell(s):
    return s.replace("|", "/")


def render(on, fetch, no_title):
    L = ["# Order-flow extraction queue (generated by rank_queue.py; do not hand-edit)", "",
         "Keywords (OURS, count of occurrences): " + ", ".join(KEYWORDS) + ". ON_DISK score = title + first 200 body "
         "lines; TO_FETCH score = title only. Ties: Tom and Fabio first, then id.", ""]
    for name, rows in (("ON_DISK", on), ("TO_FETCH", fetch)):
        L += [f"## {name} ({len(rows)})", "", "| rank | id | analyst | title | score |", "|---|---|---|---|---|"]
        L += [f"| {i} | {r['id']} | {cell(r['analyst']) or 'unknown'} | {cell(r['title'])} | {r['score']} |"
              for i, r in enumerate(rows, 1)]
        L.append("")
    L += [f"## NO_TITLE ({len(no_title)})", ""]
    L += [f"- {v} ({w})" for v, w in no_title] or ["none"]
    return "\n".join(L) + "\n"


def main():
    gaps = (HERE / "GAPS.md").read_text(encoding="utf-8")
    on, fetch, nt = build(gaps, transcript_dir(ROOT), priority_titles(ROOT), ledger_channels(HERE / "EXTRACTION_LEDGER.csv"))
    (HERE / "ORDERFLOW_QUEUE.md").write_text(render(on, fetch, nt), encoding="utf-8")
    print(f"ON_DISK {len(on)} TO_FETCH {len(fetch)} NO_TITLE {len(nt)}")


if __name__ == "__main__":
    sys.exit(main())
