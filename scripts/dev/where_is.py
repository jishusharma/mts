"""WHERE_IS: topic -> files / machine / channel / ledger row.

  python scripts/dev/where_is.py build [--root DIR]   regenerate MyTradingSys/system/WHERE_IS.md
  python scripts/dev/where_is.py <topic> [--root DIR]  case-insensitive search (exit 1 "not indexed" if none)

Sources: EXTRACTION_LEDGER.csv, WIRING_*.csv (wiring audits), layer_index.json.
Only paths that exist on disk are listed. The local operator_material_index jsonl
(F:/MTS/data/operator_material_index/<host>.jsonl) is searched on query only; its file
names are printed locally, never written to WHERE_IS.md (public repo).
DECISION (OURS): no per-machine counts file is committed anywhere, so none is read.
"""
import argparse
import csv
import glob
import json
import os
import re
import socket
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT_REL = "MyTradingSys/system/WHERE_IS.md"
LEDGER_REL = "MyTradingSys/research/extraction_ledger_2026-10/EXTRACTION_LEDGER.csv"
WIRING_GLOB = "MyTradingSys/research/wiring_audit_2026-10/WIRING_*.csv"
LAYER_REL = "MyTradingSys/system/layer_index.json"
HEADER = "| topic | path | machine | channel | note |"
_PATH_RE = re.compile(r"[A-Za-z0-9_./-]+\.(?:java|py|md|csv|json|txt|tsv)")
_WS = re.compile(r"\s+")


def clean(s):
    return _WS.sub(" ", str(s or "")).replace("|", "/").strip()


def real_path(root, text):
    """First repo-relative path in text that exists on disk, else ''."""
    for m in _PATH_RE.finditer(text or ""):
        p = m.group(0)
        if os.path.exists(os.path.join(root, p)):
            return p
    return ""


def rows_ledger(root):
    p = os.path.join(root, LEDGER_REL)
    out = []
    if not os.path.exists(p):
        return out
    for r in csv.DictReader(open(p, encoding="utf-8", newline="")):
        path = real_path(root, r.get("extract_file", ""))
        if path:
            machine = "repo"
        else:
            path = LEDGER_REL
            machine = "ledger row only (transcript %s on the host that fetched it)" % (clean(r.get("transcript_file")) or "none")
        note = "ledger: method=%s, quotes=%s/%s, used_by=%s" % (
            clean(r.get("method")) or "none", clean(r.get("quotes_verified")) or "-", clean(r.get("quotes")) or "-",
            clean(r.get("used_by")) or "none")
        out.append((clean(r["video_id"]) + " " + clean(r.get("channel")), path, machine, clean(r.get("channel")), note))
    return out


def rows_wiring(root):
    out = []
    for f in sorted(glob.glob(os.path.join(root, WIRING_GLOB))):
        rel = os.path.relpath(f, root).replace(chr(92), "/")
        for r in csv.DictReader(open(f, encoding="utf-8", newline="")):
            if not r.get("rule_id"):
                continue
            path = real_path(root, r.get("code_file_line", "")) or real_path(root, r.get("rule_file_line", "")) or rel
            note = "wiring: %s, extent=%s; audit %s" % (clean(r.get("verdict")), clean(r.get("extent")) or "-", rel)
            out.append((clean(r["rule_id"]) + " " + clean(r.get("rule"))[:80], path, "repo",
                        clean(r.get("trader")), note))
    return out


def rows_layers(root):
    p = os.path.join(root, LAYER_REL)
    out = []
    if not os.path.exists(p):
        return out
    for fam in json.load(open(p, encoding="utf-8")).get("families", []):
        for key in ("spec", "code", "results"):
            for path in fam.get(key, []) or []:
                if os.path.exists(os.path.join(root, path)):
                    out.append(("layer " + clean(fam.get("id")) + " " + clean(fam.get("name")), path, "repo",
                                clean(fam.get("id")), "layer_index %s" % key))
    return out


def build(root):
    rows = sorted(set(rows_ledger(root) + rows_wiring(root) + rows_layers(root)), key=lambda r: (r[0].lower(), r[1]))
    lines = ["# WHERE_IS (generated by scripts/dev/where_is.py build; do not edit)", "",
             "Search: `python scripts/dev/where_is.py <topic>`. Search here before saying something is not found.",
             "", HEADER, "|---|---|---|---|---|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    lines += ["", "Rows: %d. Sources: ledger, wiring audits, layer_index. Per-machine operator material is searched locally only." % len(rows), ""]
    with open(os.path.join(root, OUT_REL), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    return len(rows)


def local_hits(q):
    p = os.environ.get("WHERE_IS_LOCAL") or "F:/MTS/data/operator_material_index/%s.jsonl" % socket.gethostname().lower()
    hits = []
    if os.path.exists(p):
        for line in open(p, encoding="utf-8", errors="replace"):
            if q in line.lower():
                try:
                    d = json.loads(line)
                    hits.append("LOCAL %s | %s | %s" % (d.get("path"), d.get("kind"), ",".join(d.get("topics", []))))
                except ValueError:
                    pass
    return hits


def query(root, topic):
    q = topic.lower()
    p = os.path.join(root, OUT_REL)
    hits = []
    if os.path.exists(p):
        hits = [l for l in open(p, encoding="utf-8") if l.startswith("| ") and q in l.lower() and l.strip() != HEADER]
    return [h.strip() for h in hits] + local_hits(q)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("topic", nargs="+")
    ap.add_argument("--root", default=ROOT)
    a = ap.parse_args(argv)
    if a.topic == ["build"]:
        print("WHERE_IS.md rows: %d" % build(a.root))
        return 0
    hits = query(a.root, " ".join(a.topic))
    if not hits:
        print("not indexed: %s" % " ".join(a.topic))
        return 1
    print(HEADER)
    print("\n".join(hits))
    return 0


if __name__ == "__main__":
    sys.exit(main())
